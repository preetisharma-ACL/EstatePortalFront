import { defineConfig } from "@solidjs/start/config";
import tailwindcss from "@tailwindcss/vite";

const API = "https://api.realestate.aajneeti.social";

/**
 * The sections the backend splits its sitemap index into.
 *
 * Listed one by one because Nitro route patterns only wildcard WHOLE path
 * segments: "/sitemap-**" never matches "/sitemap-projects.xml", since the
 * wildcard would have to cover part of a segment. Verified by testing — the
 * wildcard form fell through to the app and returned the HTML shell.
 *
 * If the backend adds a section, add it here too: the index will advertise
 * the new URL immediately, and without an entry it serves the app shell to
 * crawlers instead of XML.
 */
const SITEMAP_SECTIONS = [
  "static", "cities", "property-types", "townships", "localities",
  "projects", "developers",
];

const sitemapProxies = Object.fromEntries(
  SITEMAP_SECTIONS.map((s) => [`/sitemap-${s}.xml`, { proxy: `${API}/sitemap-${s}.xml` }]),
);

export default defineConfig({
  ssr: true,
  // Static assets live under src/public (e.g. src/public/banner/*.webp),
  // served from the site root — /banner/banner-1.webp.
  publicDir: "./src/public",
  server: {
    routeRules: {
      // The homepage was server-rendered fresh on every request
      // (x-vercel-cache: MISS, 784ms TTFB). Its content is a featured/premium
      // project rail and a city list -- none of it per-visitor, and lead
      // attribution is captured client-side from window.location, so nothing
      // visitor-specific is baked into the HTML. A 60s window keeps it current
      // while serving almost every request from the edge.
      "/": { isr: { expiration: 60 } },

      // The sitemap and robots.txt are generated by the backend but must be
      // served from THIS origin: the index points at
      // realestate.aajneeti.social/sitemap-*.xml, and a sitemap may only list
      // URLs on the host serving it.
      //
      // These were `rewrites` in vercel.json, which cannot work: SolidStart
      // builds through the Build Output API, so Vercel takes its routing from
      // the generated .vercel/output/config.json and ignores vercel.json's
      // routes/rewrites/headers. Every request fell through the catch-all and
      // got the app shell as text/html. Nitro route rules DO compile into that
      // generated table.
      "/sitemap.xml": { proxy: `${API}/sitemap.xml` },
      "/robots.txt": { proxy: `${API}/robots.txt` },
      ...sitemapProxies,
    },
  },
  vite: {
    plugins: [tailwindcss()],
  },
});
